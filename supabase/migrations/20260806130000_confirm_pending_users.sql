-- СРОЧНО: разблокировать вход. По задумке вход почта+пароль идёт БЕЗ подтверждения
-- почты, но в проекте включено «Confirm email» → новые аккаунты застревают
-- (ошибка "email not confirmed"). Здесь подтверждаем все уже созданные аккаунты,
-- чтобы люди (напр. друг-тестер) сразу могли войти. Идемпотентно.
update auth.users
set email_confirmed_at = now()
where email_confirmed_at is null;
